#!/usr/bin/env python3
"""Keep docs/ a conformant Open Knowledge Format (OKF v0.2) bundle and write its index.md files.

    python3 tools/okf-index.py           # write docs/**/index.md
    python3 tools/okf-index.py --check   # exit 1 if a concept breaks the rules or an index.md is stale

Every .md under docs/ other than index.md and log.md is a concept and starts with YAML frontmatter that has
`type`, `title` and `description` (OKF requires only `type`; we require all three so the indexes read well).
Plans also carry `status` and `created`. Each directory gets a generated index.md: subdirectories first,
then concepts grouped by `type`; plans newest first. Spec: https://github.com/GoogleCloudPlatform/knowledge-catalog
(okf/SPEC.md). Pure Python 3.10+, no packages, deterministic output.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
RESERVED = {"index.md", "log.md"}
REQUIRED = ("type", "title", "description")
OKF_VERSION = "0.2"

# Directories: title and one-line description, used for their heading and for the parent's index entry.
DIRS = {
    "": ("SummonOS docs", "Everything written down about SummonOS: features, how to install and build, tools, plans and research."),
    "adr": ("Architecture decisions", "Accepted and proposed design decisions, one per file."),
    "plans": ("Plans and reports", "Finished and long plans, one per file. A plan records what was decided at the time; "
                       "when it disagrees with a project's README or PROJECT-CONTEXT.md, those win."),
    "research": ("Research", "Research notes behind the skills and the design of SummonOS apps."),
    "research/2026-10-18-mac-gui-design": ("macOS GUI design research", "Four reports on menu bar apps, Apple's design "
                                           "language, window mechanics and activity UI (2026-10-18)."),
    "ux-surfaces": ("macOS UX surfaces", "The seven kinds of Mac app surface across 14 UX dimensions, and each one "
                    "checked against Apple's HIG and API docs (2026-10-25)."),
    "assets": None,  # README art, no markdown
}
# Section order for concept types; unknown types follow alphabetically.
TYPE_ORDER = ["Reference", "Playbook", "Plan", "Report", "Research"]
SECTION = {"Reference": "Reference", "Playbook": "Guides", "Plan": "Plans", "Report": "Reports", "Research": "Research"}


def parse_frontmatter(text: str) -> dict[str, object] | None:
    """The small YAML subset we write: `key: value`, `key: [a, b]`, double-quoted strings."""
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---\n", 4)
    if end < 0:
        return None
    data: dict[str, object] = {}
    for line in text[4:end].splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not m:
            continue
        key, raw = m.group(1), m.group(2).strip()
        if raw.startswith("[") and raw.endswith("]"):
            data[key] = [v.strip() for v in raw[1:-1].split(",") if v.strip()]
        elif raw.startswith('"') and raw.endswith('"'):
            data[key] = raw[1:-1].replace('\\"', '"')
        else:
            data[key] = raw
    return data


def concepts(directory: Path) -> list[tuple[Path, dict[str, object]]]:
    out = []
    for path in sorted(directory.glob("*.md")):
        if path.name in RESERVED:
            continue
        out.append((path, parse_frontmatter(path.read_text()) or {}))
    return out


def problems() -> list[str]:
    found = []
    for path in sorted(DOCS.rglob("*.md")):
        if path.name in RESERVED:
            continue
        rel = path.relative_to(ROOT)
        fm = parse_frontmatter(path.read_text())
        if fm is None:
            found.append(f"{rel}: no YAML frontmatter")
            continue
        for key in REQUIRED:
            if not fm.get(key):
                found.append(f"{rel}: frontmatter has no `{key}`")
        if fm.get("type") == "Plan" and not (fm.get("status") and fm.get("created")):
            found.append(f"{rel}: a Plan needs `status` and `created`")
    for path in sorted(p for p in DOCS.rglob("*") if p.is_dir()):
        key = path.relative_to(DOCS).as_posix()
        if key not in DIRS and any(path.glob("*.md")):
            found.append(f"docs/{key}: add it to DIRS in tools/okf-index.py (title and description)")
    return found


def index_for(directory: Path) -> str:
    key = "" if directory == DOCS else directory.relative_to(DOCS).as_posix()
    title, blurb = DIRS[key]
    lines = []
    if key == "":
        lines += ["---", f'okf_version: "{OKF_VERSION}"', "---", "",
                  "<!-- Generated by tools/okf-index.py; edit frontmatter, not this file. -->", ""]
    else:
        lines += ["<!-- Generated by tools/okf-index.py; edit frontmatter, not this file. -->", ""]
    lines += [f"# {title}", "", blurb, ""]

    subdirs = [d for d in sorted(directory.iterdir()) if d.is_dir()
               and DIRS.get(d.relative_to(DOCS).as_posix()) is not None]
    if subdirs:
        lines += ["# Folders", ""]
        for d in subdirs:
            t, desc = DIRS[d.relative_to(DOCS).as_posix()]
            lines.append(f"* [{t}]({d.name}/index.md) - {desc}")
        lines.append("")

    groups: dict[str, list[tuple[Path, dict[str, object]]]] = {}
    for path, fm in concepts(directory):
        groups.setdefault(str(fm.get("type", "Concept")), []).append((path, fm))
    order = [t for t in TYPE_ORDER if t in groups] + sorted(t for t in groups if t not in TYPE_ORDER)
    for t in order:
        items = groups[t]
        if t in ("Plan", "Report"):
            items = sorted(items, key=lambda i: (str(i[1].get("created", "")), i[0].name), reverse=True)
        lines += [f"# {SECTION.get(t, t)}", ""]
        for path, fm in items:
            extra = ""
            if fm.get("status"):
                extra = f" ({fm['created']}, {fm['status']})" if fm.get("created") else f" ({fm['status']})"
            elif fm.get("created") and t == "Research":
                extra = f" ({fm['created']})"
            lines.append(f"* [{fm.get('title', path.stem)}]({path.name}) - {fm.get('description', '')}{extra}")
        lines.append("")
    if (directory / "log.md").exists():
        lines += ["# History", "", "* [Update log](log.md) - what changed in these docs, newest first", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def outputs() -> dict[Path, str]:
    dirs = [DOCS] + [d for d in sorted(DOCS.rglob("*")) if d.is_dir() and DIRS.get(d.relative_to(DOCS).as_posix())]
    return {d / "index.md": index_for(d) for d in dirs}


def main() -> int:
    check = "--check" in sys.argv[1:]
    bad = problems()
    if bad:
        print("okf-index: docs/ is not a conformant OKF bundle:", *bad, sep="\n  ", file=sys.stderr)
        return 1
    stale = []
    for path, content in outputs().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.write_text(content)
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("okf-index: stale, run python3 tools/okf-index.py:", *stale, sep="\n  ", file=sys.stderr)
        return 1
    if check:
        print("okf-index: docs/ is a conformant OKF bundle and its indexes are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
